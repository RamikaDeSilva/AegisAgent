class PRScanState(BaseModel):
    """
    Single source of truth for a PR scan run.

    Passed between every LangGraph node. All fields except ``pr_url`` are
    optional so partial state is always valid. Nodes must read from and
    write to this model — never pass raw dicts between nodes.
    """

    pr_url: str
    repo_name: str | None = None
    diff_text: str | None = None
    db_impacted: bool | None = None
    """Set by the Greptile node. None means not yet classified."""
    tech_stack: str | None = None
    waf_bypasses: list[str] = []
    """Set by the Nia node. Empty list means not yet fetched."""
    target_url: str | None = None
    sqlmap_result: dict | None = None
    """Set by the Muscle stream's run_sqlmap wrapper."""
    nuclei_result: dict | None = None
    """Set by the Muscle stream's run_nuclei wrapper."""
    simplified_report: str | None = None
    """LLM-generated human-readable summary; posted to the PR."""
    pending_comment_id: int | None = None
    """GitHub comment ID returned by post_pending_status; used by update_pr_comment."""
    bounty_paid: bool = False
    """Set to True after a successful AllScale payout."""
    bounty_wallet: str | None = None
    """Recipient wallet for the AllScale bounty. Sourced from BOUNTY_WALLET env."""
    bounty_amount: float = 100.0
    """Bounty payout amount. Sourced from BOUNTY_AMOUNT env (default 100.0)."""


