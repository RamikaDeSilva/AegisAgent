from __future__ import annotations

import hashlib
import hmac
import json
import logging
import os
import time
import uuid
from base64 import b64encode

import httpx
from dotenv import load_dotenv
from tenacity import (
    retry,
    retry_if_exception,
    stop_after_attempt,
    wait_exponential,
)

load_dotenv()

logger = logging.getLogger(__name__)

# Correct base URL per AllScale API docs (openapi.allscale.io, not api.allscale.io)
_ALLSCALE_API = "https://openapi.allscale.io"


# ---------------------------------------------------------------------------
# Internal helpers
# ---------------------------------------------------------------------------


def _is_retryable(exc: BaseException) -> bool:
    if isinstance(exc, httpx.HTTPStatusError):
        return exc.response.status_code in {429, 502, 503}
    return isinstance(exc, (httpx.TimeoutException, httpx.NetworkError))


_retry = retry(
    retry=retry_if_exception(_is_retryable),
    wait=wait_exponential(multiplier=1, min=1, max=10),
    stop=stop_after_attempt(3),
    reraise=True,
)


def _sign_request(
    method: str,
    path: str,
    body: str,
    query: str = "",
) -> dict[str, str]:
    """
    Build HMAC-SHA256 signed headers for the AllScale API.

    Canonical string format (joined with newlines):
        METHOD
        PATH
        QUERY_STRING
        TIMESTAMP
        NONCE
        BODY_SHA256
    """
    api_key = os.getenv("ALLSCALE_API_KEY", "")
    api_secret = os.getenv("ALLSCALE_API_SECRET", "")

    timestamp = str(int(time.time()))
    nonce = str(uuid.uuid4())

    body_hash = hashlib.sha256(body.encode()).hexdigest()

    canonical = "\n".join([
        method.upper(),
        path,
        query,
        timestamp,
        nonce,
        body_hash,
    ])

    signature = b64encode(
        hmac.new(
            api_secret.encode(),
            canonical.encode(),
            hashlib.sha256,
        ).digest()
    ).decode()

    return {
        "X-API-Key": api_key,
        "X-Timestamp": timestamp,
        "X-Nonce": nonce,
        "X-Signature": f"v1={signature}",
        "Content-Type": "application/json",
    }


