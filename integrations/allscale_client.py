async def trigger_bounty_payout(wallet_address: str, amount: float) -> bool:
    """
    Trigger an automated bounty payout via the AllScale API.

    Creates a checkout intent for a USDC payout to the given wallet address.
    Called by the Brain stream when a confirmed vulnerability is found.
    The result is stored in ``PRScanState.bounty_paid``.

    Reads ``ALLSCALE_API_KEY`` and ``ALLSCALE_API_SECRET`` from the environment.

    Args:
        wallet_address: The recipient's wallet address for the payout.
        amount: The payout amount in USDC (e.g. 10.0 = 10 USDC).

    Returns:
        True if the checkout intent was successfully created, False otherwise.
    """
    try:
        path = "/v1/checkout_intents/"
        # AllScale amount_cents = stable-coin "cents" (1.00 USDC = 100 cents)
        # Minimum is 0.1 USDC (10 cents); floor at 11 cents to stay above limit.
        amount_cents = max(int(amount * 100), 11)

        body_payload = {
            "stable_coin": 2,           # 2 = USDC per AllScale StableCoin enum
            "amount_cents": amount_cents,
            "order_id": f"aegis-bounty-{wallet_address[:8]}",
            "order_description": f"AegisAgent vulnerability bounty payout to {wallet_address}",
            "user_id": wallet_address,
        }
        body_str = json.dumps(body_payload, separators=(",", ":"))
        headers = _sign_request("POST", path, body_str)

        @_retry
        async def _post() -> bool:
            async with httpx.AsyncClient(timeout=30) as client:
                resp = await client.post(
                    f"{_ALLSCALE_API}{path}",
                    headers=headers,
                    content=body_str,
                )
                resp.raise_for_status()
                data = resp.json()
                if data.get("code") != 0:
                    logger.error(
                        "AllScale returned non-zero code %s: %s",
                        data.get("code"),
                        data.get("error"),
                    )
                    return False
                logger.info(
                    "AllScale checkout intent created: %s",
                    data.get("payload", {}).get("allscale_checkout_intent_id"),
                )
                return True

        return await _post()
    except Exception:
        logger.exception(
            "trigger_bounty_payout failed for wallet=%r amount=%s",
            wallet_address,
            amount,
        )
        return False
