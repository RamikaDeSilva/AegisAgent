from __future__ import annotations

import logging
import os

from dotenv import load_dotenv
from openai import AsyncOpenAI
from tenacity import (
    retry,
    retry_if_exception,
    stop_after_attempt,
    wait_exponential,
)

load_dotenv()

logger = logging.getLogger(__name__)

# Module-level client — reuses connection pool across all calls.
_openai_client = AsyncOpenAI(api_key=os.getenv("OPENAI_API_KEY", ""))

# Truncate diffs to stay within safe latency/cost bounds.
# gpt-4o-mini supports 128k tokens but large diffs waste time and money.
_MAX_DIFF_CHARS = 50_000


def _is_retryable(exc: BaseException) -> bool:
    """Retry on OpenAI rate limits and transient network errors."""
    try:
        import openai
        if isinstance(exc, openai.RateLimitError):
            return True
        if isinstance(exc, (openai.APIConnectionError, openai.APITimeoutError)):
            return True
    except ImportError:
        pass
    return False


_retry = retry(
    retry=retry_if_exception(_is_retryable),
    wait=wait_exponential(multiplier=1, min=2, max=10),
    stop=stop_after_attempt(3),
    reraise=True,
)


# ---------------------------------------------------------------------------
# Internal classifier — raises freely so @_retry can observe exceptions
# ---------------------------------------------------------------------------


@_retry
async def _classify(repo_name: str, diff_text: str) -> bool:
    """
    Make the OpenAI call and return the YES/NO result.

    Decorated with @_retry so tenacity can see and retry on RateLimitError,
    APIConnectionError, and APITimeoutError. Must NOT catch exceptions here —
    the public wrapper below handles the final fallback.
    """
    response = await _openai_client.chat.completions.create(
        model="gpt-4o-mini",
        messages=[
            {
                "role": "system",
                "content": "You are a security reviewer. Respond ONLY with 'YES' or 'NO'.",
            },
            {
                "role": "user",
                "content": (
                    f"Does this diff touch DB code (SQL, ORM, migrations)?\n"
                    f"Repo: {repo_name}\n\n"
                    f"{diff_text[:_MAX_DIFF_CHARS]}"
                ),
            },
        ],
        max_tokens=5,
        temperature=0,
    )
    answer = response.choices[0].message.content.strip().upper()
    return answer.startswith("YES")


# ---------------------------------------------------------------------------
# Public interface
# ---------------------------------------------------------------------------


async def analyze_diff_for_db_impact(repo_name: str, diff_text: str) -> bool:
    """
    Classify whether a PR diff touches database code.

    Returns True if the diff contains database-impacting changes — raw SQL
    queries, ORM model changes, migration files, query-builder logic, etc.
    Returns False if the diff is unrelated to the database layer.

    NOTE: Greptile v2/query returned 404 during integration (API appears
    deprecated/moved). OpenAI gpt-4o-mini is used as a binary classifier.
    Greptile repo indexing was confirmed working (202 "Repository is up to date").

    Reads ``OPENAI_API_KEY`` from the environment.

    Args:
        repo_name: The GitHub repo in ``owner/repo`` format (e.g. ``"acme/api"``).
        diff_text: The raw unified diff string returned by ``get_pr_diff``.

    Returns:
        True if the diff is DB-impacting and should trigger a sqlmap scan,
        False otherwise.
    """
    try:
        return await _classify(repo_name, diff_text)
    except Exception:
        logger.exception(
            "Classification failed for %s. Defaulting to False.", repo_name
        )
        return False
